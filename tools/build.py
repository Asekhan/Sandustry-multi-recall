"""Bundles src/ into mod/main.js (a mod entry runs inside an async IIFE: no import/export) and writes
mod/modinfo.json. `--check` fails if mod/ is stale. Python 3.10, standard library only.

    python -I tools/build.py [--check]
"""
import json
import pathlib
import sys

VERSION = "0.3.0"
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
MANIFEST = {
    "manifestVersion": 1,
    "id": "asekhan.multirecall",
    "name": "Multi-Recall",
    "version": VERSION,
    "apiVersion": 1,
    "gameVersion": {"minimum": "0.6.0"},
    "entry": "main.js",
    "author": "Asekhan",
    "description": "\n".join([
        "Keep several recall portals and pick where the Recall Shard takes you.",
        "",
        "- Right-click with the Recall Shard to place a portal. Left-click opens a ring of arrows, one per portal, with its distance.",
        "- Research Recall Network I / II / III for 2, 5, then 10 portals.",
        "- A trip burns the Voidbloom stacked above the destination portal: 48 cells by default (3x vanilla).",
        "- Trip and research costs: Options > Mods > Multi-Recall.",
    ]),
    "dependencies": [],
    "loadOrder": 1200,
}


def config_schema(config):
    """Player options (Options > Mods). Defaults come from config.json; main.js falls back to them too."""
    key = "mods|multiRecall|settings|"
    schema = {"tripCostMultiplier": {
        "type": "number", "default": config["tripCostMultiplier"], "min": 0, "max": 10, "step": 0.25,
        "labelKey": key + "tripCostMultiplier", "descriptionKey": key + "tripCostMultiplierDescription",
    }}
    for tech in config["techs"]:
        schema[tech["id"] + "CostK"] = {
            "type": "number", "default": tech["cost"] // 1000, "min": 1, "max": 500, "step": 1,
            "labelKey": key + tech["id"] + "CostK", "descriptionKey": key + tech["id"] + "CostKDescription",
        }
    return schema


def build():
    config = json.loads((SRC / "config.json").read_text(encoding="utf-8"))
    manifest = dict(MANIFEST, configSchema=config_schema(config))
    bundle = "\n".join([
        "// GENERATED by tools/build.py from src/. Edit src/, then run: python -I tools/build.py",
        f"const VERSION = {json.dumps(VERSION)};",
        f"const CONFIG = Object.freeze({json.dumps(config)});",
        (SRC / "logic.js").read_text(encoding="utf-8"),
        (SRC / "main.js").read_text(encoding="utf-8"),
    ])
    return {"main.js": bundle, "modinfo.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    out, mod = build(), ROOT / "mod"
    if "--check" in sys.argv:
        for name, content in out.items():
            p = mod / name
            if not p.exists() or p.read_text(encoding="utf-8") != content:
                sys.exit(f"mod/{name} is stale: run python -I tools/build.py")
        print("mod/ is current")
        return
    mod.mkdir(exist_ok=True)
    for name, content in out.items():
        (mod / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"Built mod/ ({len(out['main.js']) // 1024} KB main.js), version {VERSION}")


if __name__ == "__main__":
    main()
